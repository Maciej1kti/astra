import { uiLocale } from "./locale.ts";

const names = (field: "month" | "weekday", width: "long" | "short") =>
  Array.from({ length: field === "month" ? 12 : 7 }, (_, index) =>
    new Intl.DateTimeFormat(uiLocale, {
      [field]: width,
      timeZone: "UTC",
    }).format(
      new Date(
        field === "month"
          ? Date.UTC(2026, index, 1)
          : Date.UTC(2026, 0, 4 + index),
      ),
    ),
  );

